// 2026-10-13 round 76-CT: **填充色令牌 -> 文字色** 的统一工具。
//
// 背景: 平台有一批"按填充色设计"的令牌 —— --table-*(记忆/知识/实践/反思/技能)、--layer-*(守门层)、--brand。
//   它们的取值在浅色下偏亮(如 --table-practice = #D97706), 直接当**小字号文字色**用时对比度只有 ~3.2(需要 4.5)。
//   76-CM 已在 /system/guards 用 color-mix 就地修过一版; 本轮抽成公用函数, 避免各处各写一遍。
//
// 做法: 把令牌向**当前主题的文字色**混合 —— 浅色下自动变暗、暗色下自动变亮,
//   既保留"哪一类/哪一层"的色相身份, 又不用为三主题各写一套值。
//   填充(背景/图表 itemStyle)仍用**原令牌**, 只有文字用这里的结果。
export const inkOf = (token: string, pct = 55) => `color-mix(in srgb, ${token} ${pct}%, var(--text))`;
